/**
 * Get all available products.
 */
export function getAllProducts(): Product[] {
  return products;
}

/**
 * Get single product by slug.
 */
export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug.toLowerCase() === slug.toLowerCase());
}

/**
 * Get related products matching category or tags, excluding current product.
 */
export function getRelatedProducts(currentProduct: Product, limit: number = 3): Product[] {
  return products
    .filter((p) => p.id !== currentProduct.id)
    .sort((a, b) => {
      const aCategoryMatch = a.category === currentProduct.category ? 2 : 0;
      const bCategoryMatch = b.category === currentProduct.category ? 2 : 0;
      const aTagOverlap = a.tags.filter((t) => currentProduct.tags.includes(t)).length;
      const bTagOverlap = b.tags.filter((t) => currentProduct.tags.includes(t)).length;
      return (bCategoryMatch + bTagOverlap) - (aCategoryMatch + aTagOverlap);
    })
    .slice(0, limit);
}

/**
 * Get category counts for filter navigation.
 */
export function getCategoryCounts(): Record<ProductCategory, number> {
  const counts: Record<string, number> = {
    "All Products": products.length,
  };

  SHOP_CATEGORIES.forEach((cat) => {
    if (cat !== "All Products") {
      counts[cat] = products.filter((p) => p.category === cat).length;
    }
  });

  return counts as Record<ProductCategory, number>;
}
